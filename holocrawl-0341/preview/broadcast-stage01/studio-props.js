  function prop(name, width, height, draw) {
    const tile = document.createElement('canvas');
    tile.width = width * 32;
    tile.height = height * 32;
    const ctx = tile.getContext('2d');
    const paint = (color, x, y, w, h) => {
      ctx.fillStyle = color;
      ctx.fillRect(x, y, w, h);
    };
    draw(paint);
    return {name, width, height, tile};
  }

